-- Таблицы приложения
CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(50) NOT NULL UNIQUE,
    full_name VARCHAR(120) NOT NULL,
    email VARCHAR(150) NOT NULL UNIQUE,
    CONSTRAINT chk_users_username_not_blank CHECK (TRIM(username) <> ''),
    CONSTRAINT chk_users_full_name_not_blank CHECK (TRIM(full_name) <> ''),
    CONSTRAINT chk_users_email_not_blank CHECK (TRIM(email) <> '')
);

CREATE TABLE IF NOT EXISTS celestial_objects (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL UNIQUE,
    type VARCHAR(30) NOT NULL,
    min_aperture DOUBLE PRECISION NOT NULL,
    CONSTRAINT chk_celestial_objects_name_not_blank CHECK (TRIM(name) <> ''),
    CONSTRAINT chk_celestial_objects_type CHECK (
        type IN ('STAR', 'PLANET', 'MOON', 'GALAXY', 'NEBULA', 'STAR_CLUSTER', 'COMET', 'ASTEROID', 'OTHER')
    ),
    CONSTRAINT chk_celestial_objects_min_aperture CHECK (min_aperture > 0)
);

CREATE TABLE IF NOT EXISTS telescopes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL UNIQUE,
    aperture DOUBLE PRECISION NOT NULL,
    available BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT chk_telescopes_name_not_blank CHECK (TRIM(name) <> ''),
    CONSTRAINT chk_telescopes_aperture CHECK (aperture > 0)
);

CREATE TABLE IF NOT EXISTS observation_sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    celestial_object_id BIGINT NOT NULL,
    telescope_id BIGINT NOT NULL,
    observer_id BIGINT NOT NULL,
    start_time TIMESTAMP WITH TIME ZONE NOT NULL,
    end_time TIMESTAMP WITH TIME ZONE NOT NULL,
    status VARCHAR(20) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_sessions_object FOREIGN KEY (celestial_object_id)
        REFERENCES celestial_objects(id) ON DELETE CASCADE,
    CONSTRAINT fk_sessions_telescope FOREIGN KEY (telescope_id)
        REFERENCES telescopes(id) ON DELETE CASCADE,
    CONSTRAINT fk_sessions_observer FOREIGN KEY (observer_id)
        REFERENCES users(id) ON DELETE CASCADE,
    CONSTRAINT chk_sessions_period CHECK (end_time > start_time),
    CONSTRAINT chk_sessions_status CHECK (status IN ('PLANNED', 'IN_PROGRESS', 'COMPLETED', 'CANCELLED'))
);

CREATE TABLE IF NOT EXISTS observation_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id BIGINT NOT NULL,
    recorded_at TIMESTAMP WITH TIME ZONE NOT NULL,
    description VARCHAR(1000) NOT NULL,
    quality INTEGER NOT NULL,
    CONSTRAINT fk_records_session FOREIGN KEY (session_id)
        REFERENCES observation_sessions(id) ON DELETE CASCADE,
    CONSTRAINT chk_records_description_not_blank CHECK (TRIM(description) <> ''),
    CONSTRAINT chk_records_quality CHECK (quality BETWEEN 1 AND 5)
);

CREATE INDEX IF NOT EXISTS idx_sessions_object ON observation_sessions(celestial_object_id);
CREATE INDEX IF NOT EXISTS idx_sessions_telescope ON observation_sessions(telescope_id);
CREATE INDEX IF NOT EXISTS idx_sessions_observer ON observation_sessions(observer_id);
CREATE INDEX IF NOT EXISTS idx_records_session ON observation_records(session_id);

